#!/usr/bin/env node
// Builds src/agent/specs.generated.ts from catherine/specs/*.md.
// Each spec's SHA-256 is computed over the exact file bytes.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "catherine/specs";
const required = ["id", "version", "status", "approved_by", "date"];
const specs = {};
for (const file of readdirSync(dir).filter((f) => f.endsWith(".md")).sort()) {
  const raw = readFileSync(join(dir, file), "utf8");
  const sep = raw.indexOf("\n---\n");
  if (sep < 0) throw new Error(`${file}: missing '---' header separator`);
  const header = Object.fromEntries(
    raw.slice(0, sep).split("\n").filter(Boolean).map((line) => {
      const i = line.indexOf(":");
      return [line.slice(0, i).trim(), line.slice(i + 1).trim()];
    }),
  );
  for (const key of required) if (!header[key]) throw new Error(`${file}: header '${key}' is required`);
  if (!["provisional", "approved"].includes(header.status)) throw new Error(`${file}: bad status`);
  if (`${header.id}.md` !== file) throw new Error(`${file}: id must match file name`);
  specs[header.id] = {
    id: header.id,
    version: header.version,
    status: header.status,
    approvedBy: header.approved_by,
    date: header.date,
    sha256: createHash("sha256").update(raw).digest("hex"),
    text: raw.slice(sep + 5),
  };
}
const out = `// GENERATED by scripts/build-specs.mjs from catherine/specs. Do not edit.\n` +
  `export interface AgentSpec { id: string; version: string; status: "provisional" | "approved"; approvedBy: string; date: string; sha256: string; text: string }\n` +
  `export const SPECS: Record<string, AgentSpec> = ${JSON.stringify(specs, null, 2)};\n`;
writeFileSync("src/agent/specs.generated.ts", out);
console.log(`built ${Object.keys(specs).length} spec(s): ${Object.keys(specs).join(", ")}`);
